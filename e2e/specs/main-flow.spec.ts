// 数据驱动 e2e spec 骨架。
// 每个 case 用 case.id 分流到不同的断言块。
//
// beforeEach 注入 BYOK key + model + mock OpenRouter，路由 /api/projects 等
// 真实走我们的 worker（apps/api dev server）。
//
// NOTE: 这是 e2e 骨架的第一版，每个 automated case 走最少断言把链路跑通，
// 不追求覆盖深度。失败时优先 debug fixture / mock，不要为让测试过去
// 改生产代码。

import { test, expect } from '../fixtures/test-with-tracker';
import { automatedCases } from '../cases';
import { injectByok } from '../fixtures/byok';
import { mockOpenRouter } from '../fixtures/openrouter-mock';

const APP_JSX_CONTENT = `export default function App() {
  return (
    <div>
      <h1 data-testid="mock-app-heading">Mock App</h1>
      <p>Generated by Playwright.</p>
    </div>
  );
}
`;

test.describe('main flow', () => {
  test.beforeEach(async ({ page }) => {
    await injectByok(page);
    await mockOpenRouter(page, {
      artifactFiles: [{ path: 'App.jsx', content: APP_JSX_CONTENT, asset: 'App' }],
      finishWithDone: true,
    });
  });

  for (const c of automatedCases()) {
    test(c.id, async ({ page }) => {
      switch (c.id) {
        case 'home-loads':
          await runHomeLoads(page);
          break;
        case 'create-project':
          await runCreateProject(page);
          break;
        case 'send-chat-prompt':
          await runSendChatPrompt(page);
          break;
        case 'iframe-renders-default-app':
          await runIframeRendersDefaultApp(page);
          break;
        default:
          throw new Error(`No spec body for case ${c.id}`);
      }
    });
  }
});

async function runHomeLoads(page: import('@playwright/test').Page): Promise<void> {
  await page.goto('/');
  // Home 顶部 brand 标题
  await expect(page.getByText('Open Design', { exact: true })).toBeVisible();
  // Rail 上 Create 按钮（disabled until 输入 name —— 但元素可见）
  await expect(page.getByRole('button', { name: /create/i }).first()).toBeVisible();
  // BYOK 已注入 → badge 显示 'API key ✓'
  await expect(page.getByRole('button', { name: /API key ✓/i })).toBeVisible();
}

async function runCreateProject(page: import('@playwright/test').Page): Promise<void> {
  await page.goto('/');
  const nameInput = page.getByPlaceholder('Project name');
  await nameInput.fill(`E2E test ${Date.now()}`);
  // Rail 上的 Create button —— 同名按钮可能多个，用 rail 的那个（带 PlusIcon
  // 的那一个），首屏只有一个 enabled，定位 first
  const createBtn = page.getByRole('button', { name: /^create$/i });
  await createBtn.click();
  await expect(page).toHaveURL(/\/p\//, { timeout: 10_000 });
  // workspace 渲染 —— Toolbar 上有 'PREVIEW' / 'FILE TREE' 之一
  await expect(page.getByText(/^(PREVIEW|FILE TREE)/)).toBeVisible({ timeout: 15_000 });
}

async function runSendChatPrompt(page: import('@playwright/test').Page): Promise<void> {
  // 创建一个 project 然后 send prompt
  await page.goto('/');
  const nameInput = page.getByPlaceholder('Project name');
  await nameInput.fill(`E2E chat ${Date.now()}`);
  await page.getByRole('button', { name: /^create$/i }).click();
  await expect(page).toHaveURL(/\/p\//, { timeout: 10_000 });

  // ChatPanel composer textarea
  const composer = page.getByRole('textbox', { name: /chat composer/i });
  await expect(composer).toBeVisible({ timeout: 10_000 });
  await composer.fill('Build a hello world component');

  // Send button (aria-label="Send")
  const send = page.getByRole('button', { name: /^send$/i });
  await expect(send).toBeEnabled();
  await send.click();

  // 期望看到我们的 prompt 文本回显在消息列表里（user message bubble）
  await expect(page.getByText('Build a hello world component', { exact: true })).toBeVisible({
    timeout: 15_000,
  });

  // 期望看到 mock 文本（assistant 回的 content）
  await expect(page.getByText("I'll create the requested files.")).toBeVisible({
    timeout: 15_000,
  });
}

async function runIframeRendersDefaultApp(page: import('@playwright/test').Page): Promise<void> {
  await page.goto('/');
  await page.getByPlaceholder('Project name').fill(`E2E iframe ${Date.now()}`);
  await page.getByRole('button', { name: /^create$/i }).click();
  await expect(page).toHaveURL(/\/p\//, { timeout: 10_000 });

  // send prompt 触发 mock write_file(App.jsx)
  const composer = page.getByRole('textbox', { name: /chat composer/i });
  await expect(composer).toBeVisible({ timeout: 10_000 });
  await composer.fill('Generate App.jsx');
  await page.getByRole('button', { name: /^send$/i }).click();

  // 等 mock 文件落盘（assistant 文本出现说明 tool 已执行完）
  await expect(page.getByText('All done.', { exact: true })).toBeVisible({ timeout: 15_000 });

  // P0 fix (2026-05-03)：ChatPanel 不再 set_active_tab 到 file path,FileTree
  // auto-pick 直接把首次进项目落到 PREVIEW_TAB,所以不用手动点 Preview tab。
  // 等 PreviewPanel iframe 出来 + 渲染完 react component
  const previewFrame = page.frameLocator('iframe[title="Preview"]');
  await expect(previewFrame.getByTestId('mock-app-heading')).toBeVisible({
    timeout: 30_000,
  });
}
